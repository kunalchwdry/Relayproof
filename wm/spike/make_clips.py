"""Generate synthetic speech fixtures with a local, free Piper voice.

Outputs 16 kHz mono WAV files:
  clips/marked_XX.wav    - clips that will receive the AudioSeal watermark
  clips/unmarked_XX.wav  - different sentences, never watermarked (false-positive controls)
All audio is synthetic and labelled as such in the manifest.
"""
import json
import os
import wave

import numpy as np
from piper import PiperVoice

MODEL = os.path.join(os.path.dirname(__file__), "voices", "en_US-lessac-medium.onnx")
OUT = os.path.join(os.path.dirname(__file__), "clips")

MARKED_TEXT = [
    "Good morning. This is a synthetic voice note explaining the new bus timetable for Pune's central routes.",
    "Today's update: the water supply in the eastern wards will pause for two hours on Thursday afternoon.",
    "Please note that this message was generated by a text-to-speech system and is provided for testing only.",
    "The library will be open until nine in the evening during the examination week, starting next Monday.",
    "Remember to carry your ticket and a photo identity card when you visit the public health centre.",
    "This clip is a demonstration fixture for a provenance research prototype, not a real public announcement.",
]
UNMARKED_TEXT = [
    "Welcome back to the weekend cooking series. Today we will prepare a simple lentil soup with roasted garlic.",
    "The river levels have been stable all week, according to the monitoring station near the old bridge.",
    "Our next meeting will focus on budget planning, so please bring the quarterly spreadsheets with you.",
    "The museum has a new exhibit about early textile trade routes across the Deccan plateau.",
    "Thank you for listening. Make sure to subscribe if you enjoyed this short walk through local history.",
    "A gentle breeze is expected in the afternoon, with clear skies and a high of twenty eight degrees.",
]


def synth(voice, text):
    chunks = []
    rate = None
    for chunk in voice.synthesize(text):
        rate = chunk.sample_rate
        chunks.append(chunk.audio_int16_array)
    return np.concatenate(chunks), rate


def resample_16k(samples, rate):
    if rate == 16000:
        return samples
    import torch
    import torchaudio

    t = torch.tensor(samples, dtype=torch.float32).unsqueeze(0) / 32768.0
    t = torchaudio.functional.resample(t, rate, 16000)
    return (t.squeeze(0).numpy() * 32767).astype(np.int16)


def write_wav(path, samples, rate):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(samples.tobytes())


def main():
    os.makedirs(OUT, exist_ok=True)
    voice = PiperVoice.load(MODEL)
    manifest = []
    for kind, texts in (("marked", MARKED_TEXT), ("unmarked", UNMARKED_TEXT)):
        for i, text in enumerate(texts, start=1):
            samples, rate = synth(voice, text)
            samples16 = resample_16k(samples, rate)
            name = f"{kind}_{i:02d}.wav"
            write_wav(os.path.join(OUT, name), samples16, 16000)
            manifest.append({
                "file": name,
                "kind": kind,
                "text": text,
                "seconds": round(len(samples16) / 16000, 2),
                "source": "synthetic (Piper en_US-lessac-medium, local)",
            })
            print(name, manifest[-1]["seconds"], "s", flush=True)
    with open(os.path.join(OUT, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)


if __name__ == "__main__":
    main()
